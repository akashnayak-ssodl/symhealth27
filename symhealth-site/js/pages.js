function addTextElement(parent, tag, text, className) {
  const element = document.createElement(tag);
  if (className) element.className = className;
  element.textContent = text;
  parent.appendChild(element);
  return element;
}

function renderSection(container, section) {
  const block = document.createElement('section');
  block.className = 'page-section';
  addTextElement(block, 'h2', section.heading);

  (section.paragraphs || []).forEach(text => addTextElement(block, 'p', text));

  if (section.items) {
    const list = document.createElement('ul');
    list.className = 'page-list';
    section.items.forEach(text => addTextElement(list, 'li', text));
    block.appendChild(list);
  }

  if (section.cards) {
    const grid = document.createElement('div');
    grid.className = 'page-grid';
    section.cards.forEach(card => {
      const item = document.createElement('article');
      item.className = 'page-info-card';
      addTextElement(item, 'h3', card.title);
      addTextElement(item, 'p', card.text);
      grid.appendChild(item);
    });
    block.appendChild(grid);
  }

  if (section.table) {
    const wrapper = document.createElement('div');
    wrapper.className = 'page-table-wrap';
    const table = document.createElement('table');
    const head = document.createElement('thead');
    const headerRow = document.createElement('tr');
    section.table.headers.forEach(text => addTextElement(headerRow, 'th', text));
    head.appendChild(headerRow);
    table.appendChild(head);
    const body = document.createElement('tbody');
    section.table.rows.forEach(row => {
      const tableRow = document.createElement('tr');
      row.forEach(text => addTextElement(tableRow, 'td', text));
      body.appendChild(tableRow);
    });
    table.appendChild(body);
    wrapper.appendChild(table);
    block.appendChild(wrapper);
  }

  if (section.links) {
    const links = document.createElement('div');
    links.className = 'page-links';
    section.links.forEach(link => {
      const anchor = document.createElement('a');
      anchor.className = 'btn red';
      anchor.textContent = link.label;
      anchor.href = link.url;
      if (link.url.startsWith('https://')) {
        anchor.target = '_blank';
        anchor.rel = 'noopener noreferrer';
      }
      links.appendChild(anchor);
    });
    block.appendChild(links);
  }

  container.appendChild(block);
}

